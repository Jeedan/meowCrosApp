export function sortByLastUsed(items: FoodItem[]) {
	const sorted = items.sort((a, b) =>
		b.lastUsedAt
			.toLocaleDateString()
			.localeCompare(a.lastUsedAt.toLocaleDateString()),
	);
	return sorted;
}
